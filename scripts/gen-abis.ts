// Regenerates src/lib/abis.ts from Foundry artifacts so the UI can never drift
// from the contracts. Run after `forge build`:  bun run abis
import fs from 'fs'

const read = (name: string): unknown =>
  (JSON.parse(fs.readFileSync(`contracts/out/${name}.sol/${name}.json`, 'utf8')) as { abi: unknown }).abi

const out = `// GENERATED by scripts/gen-abis.ts from contracts/out — do not edit by hand.
// Regenerate with: bun run abis

export const SLOT_FACTORY_ABI = ${JSON.stringify(read('SlotFactory'), null, 2)} as const

export const SLOT_ABI = ${JSON.stringify(read('Slot'), null, 2)} as const

export const VAULT_FACTORY_ABI = ${JSON.stringify(read('VaultFactory'), null, 2)} as const

export const SLOT_VAULT_ABI = ${JSON.stringify(read('SlotVault'), null, 2)} as const
`
fs.writeFileSync('src/lib/abis.ts', out)
console.log('wrote src/lib/abis.ts')
